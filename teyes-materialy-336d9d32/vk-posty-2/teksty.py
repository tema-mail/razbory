def tekst(p):
    zag, telo = T[p['n']]
    return f"{zag}\n\n{telo.format(shag=SHAG, url=ssylka(p))}\n\n{ADRES}\n"


if __name__ == '__main__':
    tut = Path(__file__).resolve().parent
    for p in POSTY:
        t = tekst(p)
        (tut / p['papka']).mkdir(exist_ok=True)
        (tut / p['papka'] / 'post.txt').write_text(t, encoding='utf-8')
        bez = t.replace(ssylka(p), '')
